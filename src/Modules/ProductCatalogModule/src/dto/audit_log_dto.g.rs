use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AuditLogDto {
    #[serde(rename = "id")]
    pub id: String,
    #[serde(rename = "entityName")]
    pub entity_name: String,
    #[serde(rename = "entityId")]
    pub entity_id: String,
    #[serde(rename = "action")]
    pub action: String,
    #[serde(rename = "userId")]
    pub user_id: Option<String>,
    #[serde(rename = "userName")]
    pub user_name: Option<String>,
    #[serde(rename = "userGroup")]
    pub user_group: Option<String>,
    #[serde(rename = "timestamp")]
    pub timestamp: String,
    #[serde(rename = "durationMs")]
    pub duration_ms: Option<i32>,
    #[serde(rename = "statusCode")]
    pub status_code: Option<i32>,
    #[serde(rename = "requestModule")]
    pub request_module: Option<String>,
    #[serde(rename = "requestPath")]
    pub request_path: Option<String>,
    #[serde(rename = "oldValues")]
    pub old_values: Option<String>,
    #[serde(rename = "newValues")]
    pub new_values: Option<String>,
    #[serde(rename = "changedColumns")]
    pub changed_columns: Option<String>,
    #[serde(rename = "isChanged")]
    pub is_changed: Option<bool>,
    #[serde(rename = "changeSummary")]
    pub change_summary: Option<String>,
    #[serde(rename = "ipAddress")]
    pub ip_address: Option<String>,
    #[serde(rename = "userAgent")]
    pub user_agent: Option<String>,
    #[serde(rename = "clientId")]
    pub client_id: Option<String>,
    #[serde(rename = "correlationId")]
    pub correlation_id: Option<String>,
    #[serde(rename = "isSuccess")]
    pub is_success: Option<bool>,
    #[serde(rename = "errorMessage")]
    pub error_message: Option<String>,
    #[serde(rename = "hash")]
    pub hash: Option<String>,
}
